import assert from 'node:assert/strict';
import fs from 'node:fs';
const read=p=>fs.readFileSync(p,'utf8');
const sources=['dados/idiomas-core-standard.json','dados/idiomas-core-rare.json','dados/idiomas-eberron.json','dados/idiomas-outros.json'];
const rows=sources.flatMap(p=>JSON.parse(read(p))),names=rows.map(x=>x.nome);
assert.equal(rows.length,40);assert.equal(new Set(names).size,40);
for(const key of ['Kharolian','Minotaur'])assert.ok(!names.includes(key),'Idioma ainda registrado: '+key);
const html=read('idiomas.html');
assert.ok(html.includes('IDIOMAS.length !== 40'));
const m=html.match(/const TRADUCOES_IDIOMAS = (\[[^\n]*\]);/);
assert.ok(m);const map=Object.fromEntries(JSON.parse(m[1]));
const expected={Gnomish:'Gnômico',Halfling:'Pequenino','Common Sign Language':'Língua de Sinais Comum',Sylvan:'Silvestre',Tauric:'Táurico',Kenderspeak:'Fala Kender','Thieves’ Cant':'Gíria dos Ladrões',Aquan:'Aquano',Auran:'Aurano',Ignan:'Ignano',Terran:'Terrano',Loxodon:'Loxodônico'};
for(const [key,value] of Object.entries(expected))assert.equal(map[key],value,'Tradução divergente: '+key);
for(const key of ['"Minotaur"','"Kharolian"'])assert.ok(!html.includes(key),'Idioma removido reapareceu no catálogo visível: '+key);
assert.equal(JSON.parse(read('dados/biblioteca-contagens.json')).modulos.Idiomas,40);
const native=read('scripts/species-language-rules.js');
assert.ok(native.includes("[['Minotaur','Minotauro'],['Common']]"),'Espécie Minotauro deve existir sem idioma nativo próprio.');
const mechanics=read('scripts/character-builder/language-mechanics.js');
assert.ok(mechanics.includes("fixed:['Gíria dos Ladrões'],choose:1,pool:ALL_LANGUAGES"));
assert.ok(mechanics.includes('RETIRED_LANGUAGE_KEYS'));
console.log('Catálogo de 40 idiomas e localização PT-BR: OK');
