import assert from 'node:assert/strict';
import fs from 'node:fs';
const read=p=>fs.readFileSync(p,'utf8'),creation=read('criacao-personagem.html'),sheet=read('ficha-personagem.html');
const wizard=read('scripts/character-builder/wizard-ui.js'),profile=read('scripts/character-builder/profile-ui.js');
const origin=creation.split('data-wizard-panel="origem"')[1].split('data-wizard-panel="atributos"')[0];
assert.ok(creation.indexOf('data-wizard-step="raca"')<creation.indexOf('data-wizard-step="origem"'));
assert.ok(creation.indexOf('data-wizard-panel="raca"')<creation.indexOf('data-wizard-panel="origem"'));
assert.ok(wizard.indexOf("id:'raca'")<wizard.indexOf("id:'origem'"));
assert.ok(origin.indexOf('Características Físicas')<origin.indexOf('Características Pessoais'));
assert.ok(origin.indexOf('Características Pessoais')<origin.indexOf('Imagem do Personagem'));
assert.ok(origin.indexOf('Imagem do Personagem')<origin.indexOf('Antecedente'));
assert.match(creation,/id="creation-portrait-file"[^>]*accept="image\/png,image\/jpeg,image\/webp"/);
assert.match(creation,/id="creation-review-portrait"/);
assert.match(profile,/photoDataUrl\(file,\{dimension:360,maxLength:115000\}\)/);
assert.match(profile,/state\.c\.portraitDataUrl=url/);
assert.match(profile,/delete state\.c\.portraitDataUrl/);
assert.ok(creation.includes('character-pages.css')&&sheet.includes('character-pages.css'));
assert.ok(!read('scripts/app-shell.js').includes('LIBRARY_PAGES.has(currentPage())||CHARACTER_PAGES.has(currentPage()))document.body.classList.add("hub-content-light")'));
console.log('OK: criação e ficha unificadas, etapas em ordem e retrato disponível em Origem.');
