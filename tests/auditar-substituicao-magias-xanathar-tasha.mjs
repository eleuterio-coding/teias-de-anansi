import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';

const read=path=>fs.readFileSync(path,'utf8');
const cat=JSON.parse(read('dados/magias-catalogo.json'));
const xan=JSON.parse(read('dados/magias-xanathar-usuario.json'));
const tas=JSON.parse(read('dados/magias-tasha-usuario.json'));
const phb=JSON.parse(read('dados/magias-phb-2024-indice.json'));
const norm=v=>String(v??'').normalize('NFD').replace(/[\u0300-\u036f]/g,'').replace(/[^a-z0-9]+/gi,' ').trim().toLowerCase();
const by=(arr,field)=>new Map(arr.map(x=>[norm(x[field]),x]));
const byX=by(xan.itens,'nome_original');
const byT=by(tas.itens,'name');
const inX=cat.itens.filter(x=>x.fonte==='xanathar-2017');
const inT=cat.itens.filter(x=>x.fonte==='tasha-2020');
assert.equal(cat.itens.length,146,'Catálogo deve manter 146 IDs canônicos e não duplicar livros.');
assert.equal(new Set(cat.itens.map(x=>x.id)).size,146,'IDs duplicados.');
assert.equal(xan.itens.length,95,'Todas as 95 magias originais de Xanathar precisam permanecer.');
assert.equal(tas.itens.length,21,'Todas as 21 magias originais de Tasha precisam permanecer.');
assert.equal(tas.itens.filter(x=>x.statblock).length,9,'Fichas de espíritos precisam permanecer.');
assert.equal(inX.length,85,'85 definições canônicas de Xanathar substituídas.');
assert.equal(inT.length,11,'11 definições canônicas de Tasha substituídas.');
assert.equal(cat.itens.length-inX.length-inT.length,50,'Registros de outras obras devem ser preservados.');
assert.equal(cat.fontes['xanathar-2017'].titulo,"Xanathar's Guide to Everything");
assert.equal(cat.fontes['tasha-2020'].titulo,"Tasha's Cauldron of Everything");
assert.equal(cat.fontes['xanathar-2017'].url,'https://www.dndbeyond.com/sources/dnd/xgte');
assert.equal(cat.fontes['tasha-2020'].url,'https://www.dndbeyond.com/sources/dnd/tcoe');
for(const x of [...inX,...inT]){
  const orig=x.fonte==='xanathar-2017'?byX.get(norm(x.nome_original)):byT.get(norm(x.nome_original));
  assert.ok(orig,'Registro de livro antigo não presente na nova transcrição: '+x.nome_original);
  const full=x.fonte==='xanathar-2017'?orig.descricao_original_en:orig.description;
  assert.equal(x.descricao,full,'O texto primário precisa ser o PDF do usuário: '+x.nome_original);
  assert.equal(x.descricao_tipo,'texto_fornecido_usuario','Resumo antigo não deve continuar como verbete: '+x.nome_original);
  assert.equal(x.completude,'texto_integral_fornecido_usuario');
  assert.equal(x.idioma_descricao,'en');
  assert.ok(!x.descricao.startsWith('Resumo mecânico editorial:'),'Resumo obsoleto ainda visível: '+x.nome_original);
  assert.equal(x.fonte_url,cat.fontes[x.fonte].url);
  if(x.fonte==='tasha-2020'&&orig.statblock)assert.deepEqual(x.bloco_invocacao,orig.statblock,'Ficha de invocação divergente.');
}
const names=new Set([...cat.itens,...phb.itens].map(x=>norm(x.nome_original)));
assert.ok(xan.itens.every(x=>names.has(norm(x.nome_original))),'Xanathar tem magia ausente.');
assert.ok(tas.itens.every(x=>names.has(norm(x.name))),'Tasha tem magia ausente.');
assert.equal(xan.itens.filter(x=>!cat.itens.some(c=>norm(c.nome_original)===norm(x.nome_original))).length,10);
assert.equal(tas.itens.filter(x=>!cat.itens.some(c=>norm(c.nome_original)===norm(x.name))).length,9);

const html=read('magias.html'),script=html.match(/<script>([\s\S]*?)<\/script>/)?.[1];
assert.ok(script,'Script principal ausente.');
new vm.Script(script,{filename:'magias.html'});
assert.ok(script.includes("counts.set('xanathar-2017'"),'Fonte Xanathar deve incluir 95 magias.');
assert.ok(script.includes("counts.set('tasha-2020'"),'Fonte Tasha deve incluir 21 magias.');
assert.ok(!script.includes('xanathar-pdf-2017')&&!script.includes('tasha-pdf-2020'),'Filtros duplicados antigos devem sair.');
assert.ok(script.includes("x.descricao_tipo==='texto_fornecido_usuario'&&x.idioma_descricao==='en'"),'Texto novo deve ser a descrição principal.');
assert.ok(script.includes('renderTashaStatblock'),'Fichas de espíritos devem estar disponíveis.');
assert.ok(script.includes('loadXanatharProvidedTexts()')&&script.includes('loadTashaProvidedTexts()'),'Versões originais precisam permanecer visíveis.');
assert.ok(script.includes("https://www.dndbeyond.com/sources/dnd/xgte")&&script.includes("https://www.dndbeyond.com/sources/dnd/tcoe"));
assert.ok(read('scripts/character-builder/spells.js').includes('fontes-integrais2'));
assert.ok(read('scripts/character-sheet-unified-spells.js').includes('fontes-integrais2'));
assert.ok(read('scripts/gerar_magias_catalogo.py').includes('def apply_user_pdf_editions'),'Regeneração não deve restaurar resumos antigos.');
console.log('OK: 96 resumos substituídos, 95 + 21 versões de livros acessíveis sem duplicatas e fontes oficiais nomeadas.');
