import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {state} from '../scripts/character-builder/state.js';
import {backgroundSpecialFeatGrant,backgroundSpecialFeatInstance,sanitizeBackgroundSpecialFeatChoice} from '../scripts/character-builder/background-special-feat-mechanics.js';

const read=p=>JSON.parse(readFileSync(p,'utf8'));
const forge=read('dados/antecedentes-pdf-forge-2025.json');
const quick=read('dados/antecedentes-pdf-quickstone-2024.json');
const forgeFeats=read('dados/talentos-forge-2025.json');
assert.deepEqual(forge.items.map(x=>x.nome).sort(),['Archaeologist','House Agent','Inquisitive']);
assert.deepEqual(quick.items.map(x=>x.nome).sort(),['Magewright','Wandslinger']);
assert.ok(!('migracao_forge_2025' in quick),'Migração de marcas removida');
assert.deepEqual(forgeFeats.itens.map(x=>x[0]),['Boon of Siberys']);
assert.ok(!forgeFeats.itens.some(x=>x[1]==='Dragonmark'));
state.catalogs.feats=[{id:'feat:skilled',name:'Skilled',category:'Origem',prereq:'Nenhum'}];
state.catalogs.backgrounds=[{id:'bg:archaeologist',name:'Arqueólogo',source:'Eberron: Forge of the Artificer',feat:{name:'Skilled'}}];
state.catalogs.classes=[];
state.catalogs.species=[];
state.c={refs:{background:'bg:archaeologist',class:null,species:null},choices:{background:{specialFeat:'removido',specialFeatTool:'Ferramentas antigas',toolChoice:'Ferramentas antigas'},class:{level:1},species:{},feats:{},featMechanics:{},equipment:{}}};
assert.equal(backgroundSpecialFeatGrant(),null,'Antecedente comum não concede talento especial');
assert.equal(backgroundSpecialFeatInstance(),null,'Talentos especiais removidos não devem reaparecer');
assert.equal(sanitizeBackgroundSpecialFeatChoice(),true,'Escolhas antigas devem ser higienizadas');
assert.equal(state.c.choices.background.specialFeat,undefined);
assert.equal(state.c.choices.background.specialFeatTool,undefined);
assert.equal(state.c.choices.background.toolChoice,'');
assert.equal(sanitizeBackgroundSpecialFeatChoice(),false,'Sanitização deve ser idempotente');
console.log('Antecedentes sem marcas e limpeza de escolha legada: OK');
