import fs from 'node:fs';
import assert from 'node:assert/strict';
const read=p=>fs.readFileSync(p,'utf8');
const j=p=>JSON.parse(read(p));
const arms=j('cache/armas-catalogo.json').itens;
const armors=j('dados/armaduras-pdfs.json').armaduras;
const tools=j('dados/ferramentas-pdfs.json').ferramentas;
const mounts=j('dados/catalogo-montarias-veiculos-20261104.json').itens;
const gear=j('dados/equipamentos-aventura-core-pdfs.json');
const H=new Function('window',read('scripts/fabricacao-catalogo.js')+';return window.HubFabricacao')({});
assert.equal(arms.length,41);
assert.equal(arms.find(x=>x.nome==='Yklwa')?.custo,'1 PO');
assert.equal(arms.find(x=>x.nome==='Bumerangue')?.custo,'Não informado','Não inventar preço do Bumerangue');
assert.equal(tools.length,25);
assert.equal(tools.filter(x=>x.custo&&x.peso_2024).length,25);
assert.equal(tools.find(x=>x.nome==="Smith's Tools").custo,'20 PO');
assert.equal(tools.find(x=>x.nome==="Gaming Set").variantes_2024.length,4);
assert.equal(tools.find(x=>x.nome==="Musical Instrument").variantes_2024.length,10);
assert.equal(armors.length,13);
assert.ok(armors.every(x=>x.fabricacao?.fonte?.includes('L’Arsène')&&x.fabricacao?.natureza?.includes('opcional')));
assert.deepEqual(H.nonmagic('1.500 PO'),{material:'750 PO',days:150});
assert.deepEqual(H.nonmagic('15 PO'),{material:'7 PO, 5 PP',days:2});
assert.deepEqual(H.nonmagic('5 PC'),{material:'2 PC',days:1});
assert.equal(H.nonmagic('Varies'),null);
assert.equal(mounts.length,35);
assert.equal(mounts.filter(x=>x.nome==='Cavalo de Guerra').length,1);
assert.ok(mounts.find(x=>x.nome==='Cavalo de Guerra').dados.some(x=>x.includes('Preço: 400')));
assert.ok(mounts.find(x=>x.nome==='Cavalo de Guerra').dados.some(x=>x.includes('PV 19')));
assert.ok(H.magicHtml({nome:'Poção de Clarividência',bloco:'Poção, rara'},'Rara').includes('2.000'));
assert.ok(H.magicHtml({nome:'Poção de Voo',bloco:'Poção, muito rara'},'Muito rara').includes('20.000'));
assert.ok(H.magicHtml({nome:'Poções de Cura'},'Raridade variável').includes('25 PO'));
for(const path of ['scripts/fabricacao-catalogo.js','scripts/comercio-catalogos.js'])assert.doesNotThrow(()=>new Function(read(path)));
for(const page of ['armas.html','armaduras.html','ferramentas.html','equipamentos-aventura.html','itens-magicos.html'])assert.ok(read(page).includes('fabricacao-catalogo.js'),path+' sem referências de fabricação');
const commerce=read('comercio-e-despesas.html');
assert.ok(commerce.includes('comercio-catalogos.js')&&commerce.includes('Pergaminhos de Magia — custo de fabricação por nível'));
assert.equal(gear.phb.itens.length+gear.heroes.itens.length,88);
console.log('OK — economia e fabricação: valores, fontes, deduplicação, exceções, integrações e sintaxe verificadas.');
